const stored = (() => {
  try {
    return localStorage.getItem('elia-bay-locale')
  } catch {
    return null
  }
})()

export const i18n = createI18n({
  legacy: false,
  locale: stored === 'en' ? 'en' : 'el',
  fallbackLocale: 'el',
  messages,
})

export const setLocale = (locale: 'el' | 'en'): void => {
  i18n.global.locale.value = locale
  document.documentElement.lang = locale
  try {
    localStorage.setItem('elia-bay-locale', locale)
  } catch {
    /* ignore */
  }
}
